let currentLocale: AppLocale = "vi";

export function setI18nLocale(locale: AppLocale) {
  currentLocale = locale;
}

export function getI18nLocale(): AppLocale {
  return currentLocale;
}

export function hasMessageKey(key: string): key is MessageKey {
  return key in vi;
}

function interpolate(template: string, vars?: MessageVars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] == null ? "{" + name + "}" : String(vars[name]),
  );
}

export function t(locale: AppLocale, key: MessageKey, vars?: MessageVars): string {
  return interpolate(DICTS[locale]?.[key] ?? vi[key] ?? key, vars);
}

/** Translate using the active locale (stores / helpers outside React). */
export function tt(key: MessageKey, vars?: MessageVars): string {
  return t(currentLocale, key, vars);
}

export function translateSeedFieldLabel(label: string): string {
  const key = SEED_FIELD_I18N[label];
  return key ? tt(key) : label;
}

export function translateRoleLabel(roleKey: string, storedLabel?: string): string {
  const key = ROLE_I18N[roleKey];
  if (!key) return storedLabel ?? roleKey;
  if (storedLabel && storedLabel !== vi[key]) return storedLabel;
  return tt(key);
}

export function translateStatusLabel(module: string, status: string, storedLabel?: string): string {
  const key = ("status." + module + "." + status);
  if (!hasMessageKey(key)) return storedLabel ?? status;
  if (storedLabel && storedLabel !== vi[key]) return storedLabel;
  return tt(key);
}
